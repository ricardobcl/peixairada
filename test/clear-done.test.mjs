// /clear is the chat finished (2026-10-10): the same claude goes on under a new id, and the chat it left is ticked done.
// Known by the process turning up under another chat whose transcript begins with /clear — in either order, as the
// registry and the transcript land — and only then: a move into another chat (an in-app /resume) leaves the chat it
// left as it was, even when that other chat began with a /clear of its own long ago. Hand-written registry files over a
// fixture, a `sleep` as the live process; the drawer's own /clear is drawer-clear.mjs's.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { startTestServer, tmpDir, waitFor } from '../lib/testserver.mjs';
import { chatLines, slugOf } from '../scripts/fixture.mjs';

/** A transcript /clear began, as Claude Code writes it: a caveat, the command, its empty output — no one's word. */
const clearLines = (id, cwd, at = new Date()) => {
  const base = { isSidechain: false, userType: 'external', entrypoint: 'cli', cwd, sessionId: id, version: 'fixture', gitBranch: 'main', timestamp: at.toISOString() };
  return [
    { ...base, parentUuid: null, type: 'user', isMeta: true, uuid: randomUUID(), message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>' } },
    { ...base, type: 'user', uuid: randomUUID(), message: { role: 'user', content: '<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>' } },
    { ...base, type: 'system', subtype: 'local_command', content: '<local-command-stdout></local-command-stdout>', level: 'info' },
  ];
};

test('/clear ticks the chat it left done; a move into another chat does not', { timeout: 40_000 }, async () => {
  const dir = tmpDir('peix-clear-'), cwd = tmpDir('peix-cwd-'), proj = join(dir, 'projects', slugOf(cwd));
  mkdirSync(proj, { recursive: true }); mkdirSync(join(dir, 'sessions'), { recursive: true });
  const write = (id, lines) => writeFileSync(join(proj, `${id}.jsonl`), lines.map(l => JSON.stringify(l)).join('\n') + '\n');
  const ago = ms => new Date(Date.now() - ms);
  const [a, b, c, d] = [randomUUID(), randomUUID(), randomUUID(), randomUUID()];
  write(a, chatLines({ id: a, cwd, prompt: 'the first chat', reply: 'done with it', at: ago(600_000) }));
  // b: a chat a /clear began a day ago, worked in since — resumed into, it is no fresh clear
  write(b, [...clearLines(b, cwd, ago(86_400_000)), ...chatLines({ id: b, cwd, prompt: 'an older chat', reply: 'sure', at: ago(3_600_000) })]);
  const sleeper = spawn('sleep', ['60'], { stdio: 'ignore' });
  const on = id => writeFileSync(join(dir, 'sessions', `${sleeper.pid}.json`), JSON.stringify({ pid: sleeper.pid, procStart: 'Fri Oct 10 09:00:00 2026', sessionId: id, cwd, startedAt: Date.now() - 3_600_000, version: 'fixture', kind: 'interactive', entrypoint: 'cli', status: 'idle', statusUpdatedAt: Date.now() }));
  on(a);
  const srv = await startTestServer({ claudeDir: dir });
  const chat = async id => (await srv.api('api/sessions')).body.sessions.find(s => s.id === id);
  try {
    await waitFor(async () => (await chat(a))?.alive, { what: 'the first chat alive' });

    on(b);   // the process into another chat with history: an in-app /resume
    await waitFor(async () => (await chat(b))?.alive && !(await chat(a)).alive, { what: 'the process on the older chat' });
    assert.equal((await chat(a)).done, false, 'a chat left for another one is not finished');

    write(c, clearLines(c, cwd));   // /clear: the transcript first, then the registry — the order the fake writes them
    on(c);
    await waitFor(async () => (await chat(b))?.done, { what: 'the chat /clear left, ticked done' });
    assert.equal((await chat(a)).done, false, 'and nothing else');
    assert.ok((await chat(b)).doneAt, 'a tick as the ✓ makes');
    assert.match(srv.logText(), new RegExp(`chat ${b}: cleared into ${c} — done`));
    assert.equal((await chat(c)).alive, true, 'the process goes on, the new chat\'s now');

    on(d);   // and the other order: the registry names the new chat before its transcript is there
    await waitFor(async () => (await chat(d))?.alive, { what: 'the process on a chat with no transcript yet' });
    assert.equal((await chat(c)).done, false, 'not until the transcript says it was a /clear');
    write(d, clearLines(d, cwd));
    await waitFor(async () => (await chat(c))?.done, { what: 'the chat left, done once the transcript is read' });
  } finally { sleeper.kill(); await srv.stop(); }
});
