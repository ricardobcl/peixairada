// Top priority (2026-11-24, round XXX): a hand-kept order of chats at the head of the list, one for the whole board, kept
// by the server as the project pins are — `PUT /api/priority`, the `priority` event, both snapshots. A chat deleted from
// the board leaves it; a /clear in the same claude carries the slot to the chat it went on in.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawn } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { startTestServer, tmpDir, waitFor } from '../lib/testserver.mjs';
import { chatLines, defaultFixture, slugOf } from '../scripts/fixture.mjs';

/** The stream's snapshot and every event after it, as `{ event, data }`. */
async function stream(srv) {
  const res = await fetch(`${srv.url}events?key=${srv.key}`); assert.ok(res.ok, `the event stream: ${res.status}`);
  const reader = res.body.getReader(), dec = new TextDecoder(), got = [];
  const { promise: snapshot, resolve } = Promise.withResolvers();
  (async () => {
    let buf = '';
    for (;;) {
      const { value, done } = await reader.read(); if (done) break;
      buf += dec.decode(value, { stream: true });
      let i; while ((i = buf.indexOf('\n\n')) >= 0) { const m = /^event: (\w+)\ndata: (.*)$/s.exec(buf.slice(0, i)); buf = buf.slice(i + 2); if (!m) continue; const data = JSON.parse(m[2]); if (m[1] === 'snapshot') resolve(data); else got.push({ event: m[1], data }); }
    }
  })().catch(() => {});
  return { snapshot: await snapshot, got, said: () => got.filter(e => e.event === 'priority').map(e => e.data.priority), stop: () => reader.cancel().catch(() => {}) };
}
const put = (srv, body) => srv.api('api/priority', { method: 'PUT', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
const listed = async srv => (await srv.api('api/sessions')).body.priority;

test('the order is the one given, of chats the board has, once each — said, in both snapshots and kept over a restart', { timeout: 40_000 }, async () => {
  const fx = defaultFixture(tmpDir('peix-fx-')), [one, two] = fx.chats;
  const srv = await startTestServer({ claudeDir: fx.dir });
  let ev;
  try {
    ev = await stream(srv);
    assert.deepEqual(ev.snapshot.priority, [], 'none to begin with');
    const r = await put(srv, { ids: [two.id, 'no-such-chat', one.id, two.id, 5, '../x', null] });
    assert.deepEqual(r.body, { ok: true, priority: [two.id, one.id] }, 'in the order given; an unknown id, a repeat and a non-id dropped');
    await waitFor(() => ev.said().length, { what: 'the priority event' });
    assert.deepEqual(ev.said(), [[two.id, one.id]]);
    assert.deepEqual(await listed(srv), [two.id, one.id], "GET /api/sessions's");
    assert.equal((await put(srv, { ids: two.id })).status, 400, 'not an array');
    assert.equal((await put(srv, {})).status, 400, 'no ids');
    assert.deepEqual(await listed(srv), [two.id, one.id], 'a refusal changes nothing');
    assert.deepEqual(JSON.parse(readFileSync(join(srv.dir, 'state.json'), 'utf8')).priority, [two.id, one.id], 'in the state file');
    ev.stop();
    await srv.restart();
    assert.deepEqual(await listed(srv), [two.id, one.id], 'after a restart');
    ev = await stream(srv);
    assert.deepEqual(ev.snapshot.priority, [two.id, one.id], "the stream's snapshot");
    assert.deepEqual((await put(srv, { ids: [] })).body.priority, [], 'emptied');
  } finally { ev?.stop(); await srv.stop(); }
});

test('a chat deleted from the board leaves it, and is not let back in while deleted', { timeout: 30_000 }, async () => {
  const fx = defaultFixture(tmpDir('peix-fx-')), [one, two] = fx.chats;
  const srv = await startTestServer({ claudeDir: fx.dir });
  let ev;
  try {
    await put(srv, { ids: [one.id, two.id] });
    ev = await stream(srv);
    const r = await srv.post(`api/sessions/${one.id}/remove`, {});
    assert.deepEqual(r.body, { ok: true, removed: true });
    await waitFor(() => ev.said().length, { what: 'the priority event' });
    assert.deepEqual(ev.said().at(-1), [two.id]);
    assert.deepEqual(await listed(srv), [two.id]);
    assert.deepEqual((await put(srv, { ids: [one.id, two.id] })).body.priority, [two.id], 'a deleted chat is refused');
  } finally { ev?.stop(); await srv.stop(); }
});

/** A transcript /clear began, as Claude Code writes it (clear-done.test.mjs's). */
const clearLines = (id, cwd, at = new Date()) => {
  const base = { isSidechain: false, userType: 'external', entrypoint: 'cli', cwd, sessionId: id, version: 'fixture', gitBranch: 'main', timestamp: at.toISOString() };
  return [
    { ...base, parentUuid: null, type: 'user', isMeta: true, uuid: randomUUID(), message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>' } },
    { ...base, type: 'user', uuid: randomUUID(), message: { role: 'user', content: '<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>' } },
    { ...base, type: 'system', subtype: 'local_command', content: '<local-command-stdout></local-command-stdout>', level: 'info' },
  ];
};

test('a /clear in the same claude carries the slot to the chat it went on in', { timeout: 40_000 }, async () => {
  const dir = tmpDir('peix-prio-'), cwd = tmpDir('peix-cwd-'), proj = join(dir, 'projects', slugOf(cwd));
  mkdirSync(proj, { recursive: true }); mkdirSync(join(dir, 'sessions'), { recursive: true });
  const write = (id, lines) => writeFileSync(join(proj, `${id}.jsonl`), lines.map(l => JSON.stringify(l)).join('\n') + '\n');
  const [a, other, c] = [randomUUID(), randomUUID(), randomUUID()];
  write(a, chatLines({ id: a, cwd, prompt: 'the first chat', reply: 'done with it', at: new Date(Date.now() - 600_000) }));
  write(other, chatLines({ id: other, cwd, prompt: 'another chat', reply: 'sure' }));
  const sleeper = spawn('sleep', ['60'], { stdio: 'ignore' });
  const procStart = execFileSync('/bin/ps', ['-o', 'lstart=', '-p', String(sleeper.pid)], { encoding: 'utf8', env: { ...process.env, LC_ALL: 'C', TZ: 'UTC' } }).trim();
  const on = id => writeFileSync(join(dir, 'sessions', `${sleeper.pid}.json`), JSON.stringify({ pid: sleeper.pid, procStart, sessionId: id, cwd, startedAt: Date.now() - 3_600_000, version: 'fixture', kind: 'interactive', entrypoint: 'cli', status: 'idle', statusUpdatedAt: Date.now() }));
  on(a);
  const srv = await startTestServer({ claudeDir: dir });
  let ev;
  try {
    await waitFor(async () => (await srv.api('api/sessions')).body.sessions.find(s => s.id === a)?.alive, { what: 'the first chat alive' });
    await put(srv, { ids: [other, a] });
    ev = await stream(srv);
    write(c, clearLines(c, cwd));
    on(c);
    await waitFor(() => ev.said().length, { what: 'the priority event' });
    assert.deepEqual(ev.said().at(-1), [other, c], 'the new chat in the slot the old one had');
    assert.deepEqual(await listed(srv), [other, c]);
    assert.deepEqual(JSON.parse(readFileSync(join(srv.dir, 'state.json'), 'utf8')).priority, [other, c], 'kept');
  } finally { ev?.stop(); sleeper.kill(); await srv.stop(); }
});
